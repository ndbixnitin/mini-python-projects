print("======================================")
print("       EVEN OR ODD CHECKER")
print("======================================")

# Taking number from user
number = int(input("Enter a number: "))

# Check whether number is even or odd
if number % 2 == 0:
    print("\nThe number is EVEN.")
else:
    print("\nThe number is ODD.")

print("======================================")
print("        Program Completed!")
print("======================================")
